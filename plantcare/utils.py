def check_image_health(image_file, organ='leaf'):
    try:
        from PIL import Image
        name = image_file.name.lower()
        if any(k in name for k in ['healthy', 'healty', 'helthy', 'clean', 'normal']):
            return True
        if any(k in name for k in ['disease', 'diseased', 'spot', 'blight', 'mold', 'rot', 'mildew', 'rust', 'canker', 'scab', 'lesion', 'infected']):
            return False

        if organ != 'leaf':
            return True

        image_file.seek(0)
        img = Image.open(image_file).convert('RGB')
        img = img.resize((150, 150))
        pixels = list(img.getdata())
        
        green_pixels = 0
        diseased_pixels = 0
        total_non_bg = 0
        
        for r, g, b in pixels:
            # Skip backgrounds:
            if g > 40 and g > r * 1.3 and g > b * 1.3 and r < 60 and b < 60:
                continue
            if r < 35 and g < 35 and b < 35:
                continue
            if b > r * 1.1 and b > g * 1.1 and b > 40:
                continue
            if r > 220 and g > 220 and b > 220:
                continue
                
            total_non_bg += 1
            
            if g > r * 1.05 and g > b * 1.05:
                green_pixels += 1
            elif (r > g * 1.1) or (r < 110 and g < 110 and b < 110 and abs(r - g) < 20 and (r > 30 or g > 30 or b > 30)):
                diseased_pixels += 1
                
        image_file.seek(0)
        
        if total_non_bg == 0:
            return False
            
        diseased_ratio = diseased_pixels / total_non_bg
        green_ratio = green_pixels / total_non_bg
        
        if green_ratio > 0.65 and diseased_ratio < 0.12:
            return True
        if diseased_ratio > 0.08 or green_ratio < 0.40:
            return False
            
        return True
    except Exception:
        try:
            image_file.seek(0)
        except Exception:
            pass
        return True
